'use strict';

/**
 * Write supabase/setup.sql: every migration, in order, in one file.
 *
 *   npm run build:sql
 *
 * Setting the bank up should be one paste into the Supabase SQL Editor, not
 * five files run in the right order with one forgotten. Every migration is
 * guarded (create ... if not exists, add column if not exists), so running the
 * whole file again on a database that already has some of it is safe - which
 * also makes it the upgrade path: paste the latest setup.sql and run it.
 *
 * test/api.test.js fails if this file falls out of step with the migrations.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'supabase', 'migrations');
const OUT = path.join(ROOT, 'supabase', 'setup.sql');

function build() {
  const files = fs.readdirSync(DIR).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
  const parts = [
    '-- Hedgestone Global Bank - complete database setup',
    '--',
    '-- Generated by scripts/build-setup-sql.js from supabase/migrations/. Do not',
    '-- edit by hand: change a migration and run `npm run build:sql`.',
    '--',
    '-- Paste this whole file into Supabase, SQL Editor, New query, and run it.',
    '-- Safe to run more than once, and to run again after an update.',
    '--',
    '-- Afterwards, to open the /admin desk: create your login under',
    '-- Authentication, Users (tick Auto Confirm User), then run',
    '-- supabase/grant-admin.sql with your address on its marked line.',
    '',
    `-- Includes: ${files.join(', ')}`,
    '',
  ];
  files.forEach((file) => {
    parts.push(
      '',
      `-- ${'='.repeat(74)}`,
      `-- ${file}`,
      `-- ${'='.repeat(74)}`,
      '',
      fs.readFileSync(path.join(DIR, file), 'utf8').trimEnd(),
      ''
    );
  });
  return `${parts.join('\n')}\n`;
}

if (require.main === module) {
  fs.writeFileSync(OUT, build(), 'utf8');
  console.log(`[sql] wrote ${path.relative(ROOT, OUT)}`);
}

module.exports = { build, OUT };
